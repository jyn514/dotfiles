#!/bin/sh

set -e

. lib/shell/lib.sh

if [ -n "$DOAS_USER" ]; then
	SUDO_USER=$DOAS_USER
fi

here=$(realpath "$(dirname "$0")")
my_home=
if [ -n "${SUDO_USER:-}" ]; then
	if exists getent; then
		my_home=$(getent passwd "$SUDO_USER" | cut -d: -f6)
	elif is_macos; then
		my_home=$(dscl . -read "/Users/$SUDO_USER" NFSHomeDirectory | awk '{print $2}')
	else
		fail "cannot find the home directory for $SUDO_USER"
	fi
fi

render_global() {
	render_source=$1
	render_header=$2
	render_hostname=$(hostname)
	render_shebang="$(head -c2 "$render_source")"
	# #% is the PAM config header and must remain the first line.
	if [ "$render_shebang" = "#!" ] || [ "$render_shebang" = "#%" ]; then
		head -n1 "$render_source"
		if [ -n "$render_header" ]; then
			echo "$render_header"
		fi
		tail -n+2 "$render_source" | sed "s/SETUP_HOSTNAME/$render_hostname/g"
	else
		if [ -n "$render_header" ]; then
			echo "$render_header"
		fi
		sed "s/SETUP_HOSTNAME/$render_hostname/g" "$render_source"
	fi
}

has_generated_global_header() {
	header_source=$1
	header_dest=$2
	header_shebang="$(head -c2 "$header_source")"
	if [ "$header_shebang" = "#!" ] || [ "$header_shebang" = "#%" ]; then
		head -n2 "$header_dest" | tail -n1 | grep "^# Generated by .*setup_sudo.sh" >/dev/null 2>&1
	else
		head -n1 "$header_dest" | grep "^# Generated by .*setup_sudo.sh" >/dev/null 2>&1
	fi
}

managed_global_payload() {
	payload_source=$1
	payload_dest=$2
	payload_shebang="$(head -c2 "$payload_source")"
	if [ "$payload_shebang" = "#!" ] || [ "$payload_shebang" = "#%" ]; then
		head -n1 "$payload_dest"
		tail -n+3 "$payload_dest"
	else
		tail -n+2 "$payload_dest"
	fi
}

installed_global_matches() {
	if ! [ -f "$1" ] || ! [ -f "$2" ] || [ -L "$2" ]; then
		return 1
	fi

	expected_payload=$(mktemp)
	render_global "$1" '' >"$expected_payload"
	if cmp -s "$2" "$expected_payload"; then
		rm -f "$expected_payload"
		return 0
	fi

	if has_generated_global_header "$1" "$2" \
		&& managed_global_payload "$1" "$2" | cmp -s "$expected_payload" -
	then
		rm -f "$expected_payload"
		return 0
	fi

	rm -f "$expected_payload"
	return 1
}

should_copy_global() {
	local=$1
	DEST=$2
	source=$3

	if [ -e "$DEST" ] && installed_global_matches "$source" "$DEST"; then
		echo "ok, already installed: $DEST"
		return 1
	fi

	if [ -e "$DEST" ] \
		&& ! grep "^# Generated by .*setup_sudo.sh" "$DEST" >/dev/null 2>&1
	then
		echo "error: $DEST already exists, refusing to overwrite"
		exit 1
	fi

	printf 'confirm: install ./global/%s to %s? [y/N] ' "$local" "$DEST"
	read -r REPLY
	if ! [ "$REPLY" = y ]; then
		echo "ok, skipping"
		return 1
	fi
	return 0
}

copy_globals() {
	# can't use --dirty here or git will chown the index to root :/
	v="$(realpath "$0") v$(git describe --always)"
	d=$(date "+%F %T")
	for f in "$(realpath global)"/*; do
		base=$(basename "$f")
		if [ -n "${2:-}" ] && [ "$base" != "$2" ]; then continue; fi
		while IFS="=" read -r local DEST; do
			if [ "$local" = "$base" ]; then break; fi
		done < install/global.txt

		if ! [ "$1" = --force ] && ! should_copy_global "$local" "$DEST" "$f"; then continue; fi

		mkdir -p "$(dirname "$DEST")"
		{
			h="# Generated by $v from "./global/$local" at $d"
			render_global "$f" "$h"
		} >"$DEST"
		chmod a+r "$DEST"
	done
}

# this script is very opinionated. you may not want to run everything here.

install_device () {
	if [ -n "$SUDO_USER" ] && ! exists keymapp; then
		if [ -n "$IS_DEB" ]; then
			usermod -aG plugdev "$SUDO_USER"
		fi
		mkdir -p "$my_home/.local/bin"
		chown "$SUDO_USER:$SUDO_USER" "$my_home/.local/bin"
		t=$(download https://oryx.nyc3.cdn.digitaloceanspaces.com/keymapp/keymapp-latest.tar.gz)
		tar -xf "$t" -C "$my_home/.local/bin" keymapp
		chmod +x "$my_home/.local/bin/keymapp"
	fi
}

install_security () {
	if [ -z "$IS_DEB" ]; then
		return
	fi

	if ! dpkg -l unattended-upgrades >/dev/null; then
		apt-get update
		apt-get install -y unattended-upgrades
	fi
	unattended-upgrades || true
}

setup_pcscd() {
	if ! exists pcscd || ! exists systemctl; then
		return
	fi

	if systemctl cat pcscd.socket >/dev/null 2>&1; then
		systemctl enable --now pcscd.socket || return
	else
		systemctl enable --now pcscd.service || return
	fi
}

setup_browser_account() {
	if [ "$(uname -s)" != Linux ]; then
		return
	fi

	browser_login_shell=$(command -v nologin) || return
	browser_owner_group=
	browser_created=0
	if [ -n "${SUDO_USER:-}" ]; then
		browser_owner_group=$(id -gn "$SUDO_USER") || return
	fi

	if browser_entry=$(getent passwd browser); then
		IFS=: read -r _browser_name _browser_password browser_uid _browser_gid _browser_gecos browser_home browser_shell <<EOF
$browser_entry
EOF
		# Do not repurpose an unrelated account or change its existing files.
		if [ "$browser_uid" = 0 ] \
			|| [ "$(id -gn browser)" != browser ] \
			|| [ "$browser_home" != /var/lib/browser ] \
			|| [ "$browser_shell" != "$browser_login_shell" ]; then
			fail "browser account already exists with incompatible settings; leaving it unchanged"
		fi
	else
		browser_lookup_status=$?
		if [ "$browser_lookup_status" != 2 ]; then
			return "$browser_lookup_status"
		fi
		set --
		if [ -n "$browser_owner_group" ]; then
			set -- --groups "$browser_owner_group"
		fi
		useradd --system --user-group --create-home \
			--home-dir /var/lib/browser --key HOME_MODE=0700 \
			--shell "$browser_login_shell" "$@" browser || return
		browser_uid=$(id -u browser) || return
		browser_home=/var/lib/browser
		browser_created=1
	fi

	# useradd can succeed without creating the home if that path already exists.
	if [ "$(stat -c '%u:%a' "$browser_home")" != "$browser_uid:700" ]; then
		fail "browser home must be owned by browser with mode 0700; leaving it unchanged"
	fi
	if [ "$browser_created" = 1 ]; then
		printf 'Created browser account with private home /var/lib/browser\n'
	fi

	if [ -n "$browser_owner_group" ]; then
		browser_groups=$(id -Gn browser) || return
		case " $browser_groups " in
			*" $browser_owner_group "*) ;;
			*) usermod --append --groups "$browser_owner_group" browser || return;;
		esac
	else
		printf 'No invoking user; browser account has no additional desktop group configured\n'
	fi
}

reload_systemd_after_globals() {
	if exists systemctl; then
		systemctl daemon-reload
	fi
}

encrypt() {
	if fscrypt_supported; then
		encrypt_home_dir
	else
		setup_initramfs
	fi
}

fscrypt_supported() {
	if [ -z "$SUDO_USER" ]; then
		fail "don't know original user; giving up"
	fi

	fstype=$(df "$my_home" --output=fstype | tail -n1)
	[ "$fstype" = ext4 ]
}

setup_fscrypt_profile() {
	# can't be a link because we're about to encrypt the home drive
	cp "$DIR"/../../lib/02-pam-unlock.sh /etc/profile.d
	if [ -e /etc/zshenv ]; then
		zenv=/etc/zshenv
	else
		zenv=/etc/zsh/zshenv
	fi
	echo ". /etc/profile" >> "$zenv"
}

encrypt_home_dir() {
 if fscrypt status "$my_home" | grep "encrypted with fscrypt">/dev/null; then
	 return;
 fi

	dev=$(df "$my_home" --output=source | tail -n1)

	if ! dumpe2fs -h "$dev" 2>/dev/null | grep -q 'Filesystem features:.*encrypt'; then
		tune2fs -O encrypt "$dev"
	fi

	fscrypt setup --all-users
	setup_fscrypt_profile

	# this is the dangerous part
	backup=$(dirname "$my_home")/$(basename "$my_home").bak
	mv "$my_home" "$backup"
	mkdir "$my_home"
	chown "$SUDO_USER:$SUDO_USER" "$my_home"
	fscrypt encrypt --source=pam_passphrase --user="$SUDO_USER" "$my_home"
	# we have to copy anyway to encrypt, may as well use cp instead of mv so we can confirm it's correct
	rsync -azAHX --info=progress2 "$backup/" "$my_home"
	echo "setup encrypted home drive; delete backup? [y/N]" >/dev/tty
	if read -r REPLY && [ "$REPLY" = y ]; then
		echo "deleting" >&2
		rm -rf "$backup"
	else
		echo "retaining backup in $backup" >&2
	fi
}

setup_initramfs() {
	if ! exists dracut || ! [ -f /etc/dracut.conf ]; then
		fail "only know how to manage initramfs managed by dracut"
	fi
	if ! [ -e /usr/lib/dracut/modules.d/46dropbear ]; then
		echo 'kernel_cmdline=rd.neednet=1' >/etc/dracut.conf.d/network.conf
		ln -sf "$DIR/../../lib/46dropbear" /usr/lib/dracut/modules.d
		dracut --force
	fi
}

remove_unwanted () {
	if [ -n "$IS_DEB" ]; then
		apt autoremove --purge apt-xapian-index
	elif [ -n "$IS_RPM" ]; then
		# this is strictly worse than zsh's builtin `which`, lmao
		rm /etc/profile.d/which2.sh
	fi
}

DIR="$(dirname "$(realpath "$0")")"
. "$DIR"/../../lib/shell/lib.sh
if exists dpkg; then
	IS_DEB=1
elif exists dnf; then
	IS_RPM=1
elif exists apk; then
	:
elif exists pacman; then
	:
elif exists brew; then
	:
else
	echo "$0: Unsupported distro"
	exit 1
fi

main() {
	set -x
	if exists pacman; then
		# Preserve modules until reboot; only enable cleanup for future boots.
		systemctl daemon-reload
		systemctl enable linux-modules-cleanup.service
	fi
	setup_browser_account
	install_security
	install_device
	set +x
	copy_globals ''
	reload_systemd_after_globals
	setup_pcscd
	set -x

	if [ "$(uname)" = Darwin ]; then
		launchctl config user path "/usr/bin:/bin:/usr/sbin:/sbin:$(realpath "$here/../bin"):$(brew --prefix)/bin"
	fi

	remove_unwanted
	if [ -n "${SUDO_USER:-}" ]; then
		encrypt
	fi
	set +x
}

if [ $# = 0 ]; then
	echo "usage: $0 main"
	exit 1
fi

"$@"
